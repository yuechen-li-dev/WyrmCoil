#![allow(non_snake_case)]

pub use super::artifact::{CompileSourceToHlsl, EmitHlsl};
use super::diagnostic::SdslvDiagnostic;
use super::token::SdslvSpan;
use super::vdmir::*;

pub fn EmitVdMirHlsl(module: &VdMirModule) -> Result<String, Vec<SdslvDiagnostic>> {
    let mut emitter = HlslEmitter {
        Lines: vec![],
        Diagnostics: vec![],
    };
    emitter.Emit(module);
    emitter.Finish()
}

struct HlslEmitter {
    Lines: Vec<String>,
    Diagnostics: Vec<SdslvDiagnostic>,
}

impl HlslEmitter {
    fn Emit(&mut self, module: &VdMirModule) {
        self.Lines
            .push("// Generated by WyrmCoil SDSL-V.".to_string());
        if let Some(namespace) = module.Namespace() {
            self.Lines.push(format!("// namespace {namespace}"));
        }
        for item in module.Items() {
            match item {
                VdMirItem::TypeAlias {
                    Name,
                    Target,
                    Space,
                } => {
                    if let Some(space) = Space {
                        self.Lines.push(format!("// @space({space})"));
                    }
                    self.Lines
                        .push(format!("typedef {} {Name};", HlslType(Target)));
                }
                VdMirItem::Aggregate(aggregate) => self.EmitAggregate(aggregate),
                VdMirItem::Enum { Name, Variants } => {
                    for (index, variant) in Variants.iter().enumerate() {
                        self.Lines
                            .push(format!("static const int {Name}_{variant} = {index};"));
                    }
                }
                VdMirItem::LegacyInterface(name) => {
                    self.Lines
                        .push(format!("// interface {name} omitted in HLSL M3"));
                }
                VdMirItem::StorageBinding(binding) => {
                    let ty = HlslStorageType(binding.Element, binding.Writable);
                    let register = if binding.Writable { 'u' } else { 't' };
                    self.Lines.push("#ifdef __spirv__".to_string());
                    self.Lines
                        .push(format!("[[vk::binding({}, 0)]]", binding.Binding));
                    self.Lines.push("#endif".to_string());
                    self.Lines.push(format!(
                        "{ty} {} : register({register}{});",
                        binding.Name, binding.Binding
                    ));
                }
                VdMirItem::Function(function) => self.EmitFunction(function),
                VdMirItem::Flow(flow) => self.EmitFlow(flow),
            }
        }
    }

    fn EmitAggregate(&mut self, aggregate: &VdMirAggregate) {
        let name = &aggregate.Name;
        self.Lines.push(format!("struct {name} {{"));
        for field in &aggregate.Fields {
            let ty = HlslType(&field.Type);
            if let Some(role) = field.Role {
                self.EmitGraphicsField(&ty, &field.Name, role);
            } else {
                self.Lines.push(format!("    {ty} {};", field.Name));
            }
        }
        self.Lines.push("};".to_string());
        if !aggregate.HasConstructor || aggregate.Fields.is_empty() {
            return;
        }
        let parameters: Vec<_> = aggregate
            .Fields
            .iter()
            .enumerate()
            .map(|(index, field)| format!("{} value{index}", HlslType(&field.Type)))
            .collect();
        let parameters = parameters.join(", ");
        self.Lines
            .push(format!("{name} __sdslv_make_{name}({parameters}) {{"));
        self.Lines.push(format!("    {name} result;"));
        for (index, field) in aggregate.Fields.iter().enumerate() {
            self.Lines
                .push(format!("    result.{} = value{index};", field.Name));
        }
        self.Lines.push("    return result;".to_string());
        self.Lines.push("}".to_string());
    }

    fn EmitGraphicsField(&mut self, ty: &str, name: &str, role: VdMirFieldRole) {
        let semantic = match role {
            VdMirFieldRole::Location(index, interpolation) => {
                let qualifier = match interpolation {
                    VdMirInterpolation::Flat => "nointerpolation ",
                    VdMirInterpolation::NoPerspective => "noperspective ",
                    VdMirInterpolation::Linear => "",
                };
                self.Lines.push("#ifdef __spirv__".to_string());
                self.Lines.push(format!("    [[vk::location({index})]]"));
                self.Lines.push("#endif".to_string());
                self.Lines
                    .push(format!("    {qualifier}{ty} {name} : TEXCOORD{index};"));
                return;
            }
            VdMirFieldRole::Target(index) => format!("SV_Target{index}"),
            VdMirFieldRole::Builtin(VdMirBuiltin::VertexId) => "SV_VertexID".to_string(),
            VdMirFieldRole::Builtin(VdMirBuiltin::InstanceId) => "SV_InstanceID".to_string(),
            VdMirFieldRole::Builtin(VdMirBuiltin::FrontFace) => "SV_IsFrontFace".to_string(),
            VdMirFieldRole::Builtin(VdMirBuiltin::DispatchId) => "SV_DispatchThreadID".to_string(),
            VdMirFieldRole::Builtin(VdMirBuiltin::GroupId) => "SV_GroupID".to_string(),
            VdMirFieldRole::Builtin(VdMirBuiltin::GroupThreadId) => "SV_GroupThreadID".to_string(),
            VdMirFieldRole::Builtin(VdMirBuiltin::GroupIndex) => "SV_GroupIndex".to_string(),
            VdMirFieldRole::Builtin(VdMirBuiltin::Position) | VdMirFieldRole::ClipPosition => {
                "SV_Position".to_string()
            }
            VdMirFieldRole::LegacyLocation(index) => format!("TEXCOORD{index}"),
        };
        self.Lines.push(format!("    {ty} {name} : {semantic};"));
    }

    fn EmitFunction(&mut self, function: &VdMirFunction) {
        let target = match function.Entry.as_ref().map(|entry| entry.Kind) {
            Some(VdMirEntryKind::Pixel(VdMirPixelOutput::Scalar)) => " : SV_Target",
            Some(VdMirEntryKind::Compute(Some([x, y, z]))) => {
                self.Lines.push(format!("[numthreads({x}, {y}, {z})]"));
                ""
            }
            Some(VdMirEntryKind::Compute(None)) => {
                let program = &function.Entry.as_ref().unwrap().Program;
                self.ErrorAt(
                    &format!(
                        "unsupported stage 'compute' for HLSL M3 emission in shader '{program}'"
                    ),
                    function.Span,
                );
                return;
            }
            _ => "",
        };
        let return_type = HlslType(&function.ReturnType);
        let parameters = HlslParameters(&function.Parameters);
        self.Lines.push(format!(
            "{return_type} {}({parameters}){target} {{",
            function.Name
        ));
        let mut with_counter = 0;
        let mut utility_counter = 0;
        for statement in &function.Body {
            let lines = self.EmitStatementLines(
                statement,
                &return_type,
                &mut with_counter,
                &mut utility_counter,
            );
            for line in lines {
                self.Lines.push(format!("    {line}"));
            }
        }
        self.Lines.push("}".to_string());
    }

    fn EmitStatementLines(
        &mut self,
        statement: &VdMirStatement,
        return_type: &str,
        with_counter: &mut usize,
        utility_counter: &mut usize,
    ) -> Vec<String> {
        match statement {
            VdMirStatement::Let {
                Name,
                Type,
                Initializer,
                ..
            } => {
                let rendered = HlslType(Type);
                if let Some(init) = Initializer {
                    if let VdMirValueKind::ArrayLiteral { Elements, .. } = &init.Kind {
                        let mut lines = vec![format!("{} {};", rendered, Name)];
                        for (index, element) in Elements.iter().enumerate() {
                            lines.push(format!(
                                "{}[{}] = {};",
                                Name,
                                index,
                                self.EmitExpression(element, 0)
                            ));
                        }
                        return lines;
                    }
                    if let VdMirValueKind::Switch {
                        Subject,
                        Cases,
                        ElseValue,
                        ..
                    } = &init.Kind
                    {
                        let mut lines = vec![format!("{} {};", rendered, Name)];
                        lines.extend(self.EmitSwitchChainLines(
                            Subject.as_deref(),
                            Cases,
                            ElseValue,
                            &format!("{Name} = {{value}};"),
                            "if",
                        ));
                        return lines;
                    }
                    if let VdMirValueKind::Match { Subject, Arms, .. } = &init.Kind {
                        let mut lines = vec![format!("{} {};", rendered, Name)];
                        lines.extend(self.EmitMatchChainLines(
                            Subject,
                            Arms,
                            &format!("{Name} = {{value}};"),
                        ));
                        return lines;
                    }
                    if let VdMirValueKind::WhenUtility {
                        Cases, ElseValue, ..
                    } = &init.Kind
                    {
                        return self.EmitWhenUtilityLines(
                            Cases,
                            ElseValue,
                            Name,
                            Some(rendered.as_str()),
                            utility_counter,
                        );
                    }
                    if let VdMirValueKind::With { Base, Updates } = &init.Kind {
                        let mut lines = vec![format!(
                            "{} {} = {};",
                            rendered,
                            Name,
                            self.EmitExpression(Base, 0)
                        )];
                        for update in Updates {
                            lines.push(format!(
                                "{}.{} = {};",
                                Name,
                                update.Field,
                                self.EmitExpression(&update.Value, 0)
                            ));
                        }
                        lines
                    } else {
                        if Self::ExpressionContainsWhenUtility(init) {
                            self.Err("when utility expression is not supported in this expression context in SDSL-V M66b");
                        }
                        if Self::ExpressionContainsMatch(init) {
                            self.Err("match expression is not supported in this expression context in SDSL-V M64c");
                        }
                        vec![format!(
                            "{} {} = {};",
                            rendered,
                            Name,
                            self.EmitExpression(init, 0)
                        )]
                    }
                } else {
                    vec![format!("{} {};", rendered, Name)]
                }
            }
            VdMirStatement::Assign { Target, Value, .. } => {
                if let VdMirValueKind::ArrayLiteral { Elements, .. } = &Value.Kind {
                    let target_text = self.EmitExpression(Target, 0);
                    let mut lines = vec![];
                    for (index, element) in Elements.iter().enumerate() {
                        lines.push(format!(
                            "{}[{}] = {};",
                            target_text,
                            index,
                            self.EmitExpression(element, 0)
                        ));
                    }
                    return lines;
                }
                if let VdMirValueKind::Switch {
                    Subject,
                    Cases,
                    ElseValue,
                    ..
                } = &Value.Kind
                {
                    let target_text = self.EmitExpression(Target, 0);
                    return self.EmitSwitchChainLines(
                        Subject.as_deref(),
                        Cases,
                        ElseValue,
                        &format!("{target_text} = {{value}};"),
                        "if",
                    );
                }
                if let VdMirValueKind::Match { Subject, Arms, .. } = &Value.Kind {
                    let target_text = self.EmitExpression(Target, 0);
                    return self.EmitMatchChainLines(
                        Subject,
                        Arms,
                        &format!("{target_text} = {{value}};"),
                    );
                }
                if let VdMirValueKind::WhenUtility {
                    Cases, ElseValue, ..
                } = &Value.Kind
                {
                    let target_text = self.EmitExpression(Target, 0);
                    return self.EmitWhenUtilityLines(
                        Cases,
                        ElseValue,
                        &target_text,
                        None,
                        utility_counter,
                    );
                }
                if let VdMirValueKind::With { Base, Updates } = &Value.Kind {
                    let target_text = self.EmitExpression(Target, 0);
                    let mut lines = vec![format!(
                        "{} = {};",
                        target_text,
                        self.EmitExpression(Base, 0)
                    )];
                    for update in Updates {
                        lines.push(format!(
                            "{}.{} = {};",
                            target_text,
                            update.Field,
                            self.EmitExpression(&update.Value, 0)
                        ));
                    }
                    lines
                } else {
                    if Self::ExpressionContainsWhenUtility(Value) {
                        self.Err("when utility expression is not supported in this expression context in SDSL-V M66b");
                    }
                    if Self::ExpressionContainsMatch(Value) {
                        self.Err("match expression is not supported in this expression context in SDSL-V M64c");
                    }
                    vec![format!(
                        "{} = {};",
                        self.EmitExpression(Target, 0),
                        self.EmitExpression(Value, 0)
                    )]
                }
            }
            VdMirStatement::Return { Value } => {
                if let VdMirValueKind::Switch {
                    Subject,
                    Cases,
                    ElseValue,
                    ..
                } = &Value.Kind
                {
                    return self.EmitSwitchChainLines(
                        Subject.as_deref(),
                        Cases,
                        ElseValue,
                        "return {value};",
                        "if",
                    );
                }
                if let VdMirValueKind::Match { Subject, Arms, .. } = &Value.Kind {
                    return self.EmitMatchChainLines(Subject, Arms, "return {value};");
                }
                if let VdMirValueKind::WhenUtility {
                    Cases, ElseValue, ..
                } = &Value.Kind
                {
                    let temp_name = format!("__utility_result{}", *utility_counter);
                    let mut lines = self.EmitWhenUtilityLines(
                        Cases,
                        ElseValue,
                        &temp_name,
                        Some(return_type),
                        utility_counter,
                    );
                    lines.push(format!("return {};", temp_name));
                    return lines;
                }
                if let VdMirValueKind::With { Base, Updates } = &Value.Kind {
                    let temp_name = format!("__with{}", *with_counter);
                    *with_counter += 1;
                    let mut lines = vec![format!(
                        "auto {} = {};",
                        temp_name,
                        self.EmitExpression(Base, 0)
                    )];
                    for update in Updates {
                        lines.push(format!(
                            "{}.{} = {};",
                            temp_name,
                            update.Field,
                            self.EmitExpression(&update.Value, 0)
                        ));
                    }
                    lines.push(format!("return {};", temp_name));
                    lines
                } else {
                    if Self::ExpressionContainsWhenUtility(Value) {
                        self.Err("when utility expression is not supported in this expression context in SDSL-V M66b");
                    }
                    if Self::ExpressionContainsMatch(Value) {
                        self.Err("match expression is not supported in this expression context in SDSL-V M64c");
                    }
                    vec![format!("return {};", self.EmitExpression(Value, 0))]
                }
            }
            VdMirStatement::Expression { Value } => {
                vec![format!("{};", self.EmitExpression(Value, 0))]
            }
            VdMirStatement::Empty => vec![";".to_string()],
            VdMirStatement::ReturnVoid => vec!["return;".to_string()],
            VdMirStatement::If {
                Condition,
                ThenBody,
                ElseBody,
                ..
            } => {
                let mut lines = vec![format!("if ({}) {{", self.EmitExpression(Condition, 0))];
                for nested in ThenBody {
                    for nested_line in
                        self.EmitStatementLines(nested, return_type, with_counter, utility_counter)
                    {
                        lines.push(format!("    {}", nested_line));
                    }
                }
                lines.push("}".to_string());
                if let Some(else_body) = ElseBody {
                    lines.push("else {".to_string());
                    for nested in else_body {
                        for nested_line in self.EmitStatementLines(
                            nested,
                            return_type,
                            with_counter,
                            utility_counter,
                        ) {
                            lines.push(format!("    {}", nested_line));
                        }
                    }
                    lines.push("}".to_string());
                }
                lines
            }
            VdMirStatement::For {
                Iterator,
                Start,
                End,
                Step,
                Body,
                ..
            } => {
                let step_text = Step
                    .as_ref()
                    .map(|value| self.EmitExpression(value, 0))
                    .unwrap_or("1".to_string());
                let mut lines = vec![format!(
                    "for (int {} = {}; {} < {}; {} = {} + {}) {{",
                    Iterator,
                    self.EmitExpression(Start, 0),
                    Iterator,
                    self.EmitExpression(End, 0),
                    Iterator,
                    Iterator,
                    step_text
                )];
                for nested in Body {
                    for nested_line in
                        self.EmitStatementLines(nested, return_type, with_counter, utility_counter)
                    {
                        lines.push(format!("    {}", nested_line));
                    }
                }
                lines.push("}".to_string());
                lines
            }
        }
    }
    fn EmitWhenUtilityLines(
        &mut self,
        cases: &[VdMirUtilityCase],
        else_value: &VdMirValue,
        result_target: &str,
        result_decl_type: Option<&str>,
        utility_counter: &mut usize,
    ) -> Vec<String> {
        if Self::ExpressionContainsWhenUtility(else_value)
            || cases.iter().any(|c| {
                Self::ExpressionContainsWhenUtility(&c.Guard)
                    || Self::ExpressionContainsWhenUtility(&c.Score)
                    || Self::ExpressionContainsWhenUtility(&c.Value)
            })
        {
            self.Err("when utility expression is not supported in this expression context in SDSL-V M66b");
            return vec!["/* when utility expression is not supported in this expression context in SDSL-V M66b */".to_string()];
        }
        let id = *utility_counter;
        *utility_counter += 1;
        let mut lines = vec![];
        if let Some(t) = result_decl_type {
            lines.push(format!(
                "{} {} = {};",
                t,
                result_target,
                self.EmitExpression(else_value, 0)
            ));
        } else {
            lines.push(format!(
                "{} = {};",
                result_target,
                self.EmitExpression(else_value, 0)
            ));
        }
        lines.push(format!("bool __utility_has{} = false;", id));
        lines.push(format!("float __utility_score{} = 0.0;", id));
        for (index, case) in cases.iter().enumerate() {
            lines.push(format!("if ({}) {{", self.EmitExpression(&case.Guard, 0)));
            lines.push(format!(
                "    float __utility_case_score{} = {};",
                index,
                self.EmitExpression(&case.Score, 0)
            ));
            lines.push(format!(
                "    if (!__utility_has{} || __utility_case_score{} > __utility_score{}) {{",
                id, index, id
            ));
            lines.push(format!("        __utility_has{} = true;", id));
            lines.push(format!(
                "        __utility_score{} = __utility_case_score{};",
                id, index
            ));
            lines.push(format!(
                "        {} = {};",
                result_target,
                self.EmitExpression(&case.Value, 0)
            ));
            lines.push("    }".to_string());
            lines.push("}".to_string());
        }
        lines
    }

    fn EmitMatchChainLines(
        &mut self,
        subject: &VdMirValue,
        arms: &[VdMirMatchArm],
        template: &str,
    ) -> Vec<String> {
        let mut lines = vec![];
        if arms.is_empty() {
            self.Err("match expression is not supported in this expression context in SDSL-V M64c");
            return vec![
                "/* match expression is not supported in this expression context in SDSL-V M64c */"
                    .to_string(),
            ];
        }
        let subject_text = self.EmitExpression(subject, 0);
        for (index, arm) in arms.iter().enumerate() {
            let keyword = if index == 0 {
                "if"
            } else if index == arms.len() - 1 {
                "else"
            } else {
                "else if"
            };
            if keyword == "else" {
                lines.push("else {".to_string());
            } else {
                let variant_text = format!("{}_{}", arm.Enum, arm.Variant);
                lines.push(format!(
                    "{} ({} == {}) {{",
                    keyword, subject_text, variant_text
                ));
            }
            lines.push(format!(
                "    {}",
                template.replace("{value}", &self.EmitExpression(&arm.Value, 0))
            ));
            lines.push("}".to_string());
        }
        lines
    }

    fn EmitSwitchChainLines(
        &mut self,
        subject: Option<&VdMirValue>,
        cases: &[VdMirSwitchCase],
        else_value: &VdMirValue,
        template: &str,
        first_keyword: &str,
    ) -> Vec<String> {
        let mut lines = vec![];
        if cases.is_empty() {
            self.Err("switch expression is not supported in this expression context in M55c");
            return vec![
                "/* switch expression is not supported in this expression context in M55c */"
                    .to_string(),
            ];
        }
        for (index, case) in cases.iter().enumerate() {
            let keyword = if index == 0 { first_keyword } else { "else if" };
            let condition = if let Some(subject) = subject {
                format!(
                    "{} == {}",
                    self.EmitExpression(subject, 0),
                    self.EmitExpression(&case.Condition, 0)
                )
            } else {
                self.EmitExpression(&case.Condition, 0)
            };
            lines.push(format!("{} ({}) {{", keyword, condition));
            lines.push(format!(
                "    {}",
                template.replace("{value}", &self.EmitExpression(&case.Value, 0))
            ));
            lines.push("}".to_string());
        }
        lines.push("else {".to_string());
        lines.push(format!(
            "    {}",
            template.replace("{value}", &self.EmitExpression(else_value, 0))
        ));
        lines.push("}".to_string());
        lines
    }

    fn ExpressionContainsMatch(expression: &VdMirValue) -> bool {
        expression.AnyInTree(|kind| matches!(kind, VdMirValueKind::Match { .. }))
    }

    fn ExpressionContainsWhenUtility(expression: &VdMirValue) -> bool {
        expression.AnyInTree(|kind| matches!(kind, VdMirValueKind::WhenUtility { .. }))
    }

    fn EmitExpression(&self, expression: &VdMirValue, parent_prec: u8) -> String {
        match &expression.Kind {
            VdMirValueKind::Name(x) => x.clone(),
            VdMirValueKind::IntegerLiteral(x) => x.clone(),
            VdMirValueKind::FloatLiteral(x) => x.clone(),
            VdMirValueKind::StringLiteral(x) => format!("\"{}\"", x),
            VdMirValueKind::BoolLiteral(v) => {
                if *v {
                    "true".to_string()
                } else {
                    "false".to_string()
                }
            }
            VdMirValueKind::ArrayLiteral { .. } => {
                "/* array literal requires expected context */".to_string()
            }
            VdMirValueKind::FieldAccess { Base, Field } => {
                format!("{}.{}", self.EmitExpression(Base, 13), Field)
            }
            VdMirValueKind::Index { Base, Index, .. } => {
                format!(
                    "{}[{}]",
                    self.EmitExpression(Base, 13),
                    self.EmitExpression(Index, 0)
                )
            }
            VdMirValueKind::Call { Callee, Arguments } => {
                let mut rendered = vec![];
                for arg in Arguments {
                    rendered.push(self.EmitExpression(arg, 0));
                }
                format!(
                    "{}({})",
                    self.EmitExpression(Callee, 13),
                    rendered.join(", ")
                )
            }
            VdMirValueKind::Unary { Operator, Operand } => {
                let op = match Operator {
                    SdslvUnaryOperator::Negate => "-",
                    SdslvUnaryOperator::Not => "!",
                    SdslvUnaryOperator::BitNot => "~",
                };
                let operand = self.EmitExpression(Operand, 13);
                let text = format!("{op}{operand}");
                if parent_prec > 12 { format!("({text})") } else { text }
            }
            VdMirValueKind::Binary {
                Left,
                Operator,
                Right,
            } => {
                let (op, prec) = match Operator {
                    SdslvBinaryOperator::Or => ("||", 1),
                    SdslvBinaryOperator::And => ("&&", 2),
                    SdslvBinaryOperator::BitOr => ("|", 3),
                    SdslvBinaryOperator::BitXor => ("^", 4),
                    SdslvBinaryOperator::BitAnd => ("&", 5),
                    SdslvBinaryOperator::Equal => ("==", 6),
                    SdslvBinaryOperator::NotEqual => ("!=", 6),
                    SdslvBinaryOperator::Less => ("<", 7),
                    SdslvBinaryOperator::LessEqual => ("<=", 7),
                    SdslvBinaryOperator::Greater => (">", 7),
                    SdslvBinaryOperator::GreaterEqual => (">=", 7),
                    SdslvBinaryOperator::ShiftLeft => ("<<", 8),
                    SdslvBinaryOperator::ShiftRight => (">>", 8),
                    SdslvBinaryOperator::Add => ("+", 9),
                    SdslvBinaryOperator::Subtract => ("-", 9),
                    SdslvBinaryOperator::Multiply => ("*", 10),
                    SdslvBinaryOperator::Divide => ("/", 10),
                    SdslvBinaryOperator::Remainder => ("%", 10),
                };
                let right = if matches!(Operator, SdslvBinaryOperator::ShiftLeft | SdslvBinaryOperator::ShiftRight) {
                    format!("({} & 31u)", self.EmitExpression(Right, 6))
                } else {
                    self.EmitExpression(Right, prec + 1)
                };
                let text = format!(
                    "{} {} {}",
                    self.EmitExpression(Left, prec),
                    op,
                    right
                );
                if prec < parent_prec {
                    format!("({})", text)
                } else {
                    text
                }
            }
            VdMirValueKind::Convert(operand) => {
                format!("{}({})", HlslType(&expression.Type), self.EmitExpression(operand, 0))
            }
            VdMirValueKind::Construct { Aggregate, Arguments } => {
                let args: Vec<_> = Arguments.iter().map(|value| self.EmitExpression(value, 0)).collect();
                format!("__sdslv_make_{Aggregate}({})", args.join(", "))
            }
            VdMirValueKind::EnumVariant { Enum, Variant } => format!("{Enum}_{Variant}"),
            VdMirValueKind::With { .. } => "/*with-unsupported*/".to_string(),
            VdMirValueKind::Switch { .. } => {
                "/* switch expression is not supported in this expression context in M55c */"
                    .to_string()
            }
            VdMirValueKind::Match { .. } => {
                "/* match expression is not supported in this expression context in SDSL-V M64c */"
                    .to_string()
            }
            VdMirValueKind::WhenUtility { .. } => {"/* when utility expression is not supported in this expression context in SDSL-V M66b */".to_string()}

        }
    }

    fn EmitFlow(&mut self, flow: &VdMirFlow) {
        let return_type = HlslType(&flow.ReturnType);
        let parameters = HlslParameters(&flow.Parameters);
        self.Lines
            .push(format!("{return_type} {}({parameters}) {{", flow.Name));
        for field in &flow.Board {
            let ty = HlslType(&field.Type);
            let init = match field.Type.Physical() {
                VdMirType::Scalar(VdMirScalar::Bool) => "false".to_string(),
                VdMirType::Scalar(VdMirScalar::F32) => "0.0".to_string(),
                VdMirType::FloatVector(width) => {
                    format!("{ty}({})", vec!["0.0"; usize::from(*width)].join(", "))
                }
                _ => "0".to_string(),
            };
            self.Lines
                .push(format!("    {ty} {} = {init};", field.Name));
        }
        if !flow.Board.is_empty() {
            self.Lines.push(String::new());
        }
        self.EmitFlowState(flow, 0, 1);
        self.Lines.push("}".to_string());
    }

    fn EmitFlowState(&mut self, flow: &VdMirFlow, state: usize, depth: usize) {
        let state = &flow.States[state];
        let indent = "    ".repeat(depth);
        for write in &state.Writes {
            let value = self.EmitExpression(&write.Value, 0);
            self.Lines
                .push(format!("{indent}{} = {value};", write.Field));
        }
        match &state.Terminator {
            VdMirFlowTerminator::Return(value) => {
                let value = self.EmitExpression(value, 0);
                self.Lines.push(format!("{indent}return {value};"));
            }
            VdMirFlowTerminator::Goto(target) => self.EmitFlowState(flow, *target, depth),
            VdMirFlowTerminator::Branch { Cases, Fallback } => {
                for (index, (condition, exit)) in Cases.iter().enumerate() {
                    let keyword = if index == 0 { "if" } else { "else if" };
                    let condition = self.EmitExpression(condition, 0);
                    self.Lines
                        .push(format!("{indent}{keyword} ({condition}) {{"));
                    self.EmitFlowExit(flow, exit, depth + 1);
                    self.Lines.push(format!("{indent}}}"));
                }
                self.Lines.push(format!("{indent}else {{"));
                self.EmitFlowExit(flow, Fallback, depth + 1);
                self.Lines.push(format!("{indent}}}"));
            }
        }
    }

    fn EmitFlowExit(&mut self, flow: &VdMirFlow, exit: &VdMirFlowExit, depth: usize) {
        match exit {
            VdMirFlowExit::Goto(target) => self.EmitFlowState(flow, *target, depth),
            VdMirFlowExit::Return(value) => {
                let indent = "    ".repeat(depth);
                let value = self.EmitExpression(value, 0);
                self.Lines.push(format!("{indent}return {value};"));
            }
        }
    }

    fn Err(&mut self, message: &str) {
        self.ErrorAt(message, None);
    }

    fn ErrorAt(&mut self, message: &str, span: Option<SdslvSpan>) {
        let span = span.unwrap_or(SdslvSpan {
            Start: 0,
            End: 0,
            Line: 1,
            Column: 1,
        });
        self.Diagnostics.push(SdslvDiagnostic::New(message, span));
    }

    fn Finish(self) -> Result<String, Vec<SdslvDiagnostic>> {
        if self.Diagnostics.is_empty() {
            Ok(self.Lines.join("\n"))
        } else {
            Err(self.Diagnostics)
        }
    }
}

fn HlslParameters(parameters: &[VdMirParameter]) -> String {
    let values: Vec<_> = parameters
        .iter()
        .map(|parameter| format!("{} {}", HlslType(&parameter.Type), parameter.Name))
        .collect();
    values.join(", ")
}

fn HlslStorageType(element: VdMirStorageElement, writable: bool) -> String {
    let buffer = if writable {
        "RWStructuredBuffer"
    } else {
        "StructuredBuffer"
    };
    let element = match element {
        VdMirStorageElement::F32 => "float",
        VdMirStorageElement::I32 => "int",
        VdMirStorageElement::U32 => "uint",
        VdMirStorageElement::Float4 => "float4",
    };
    format!("{buffer}<{element}>")
}

fn HlslType(ty: &VdMirType) -> String {
    let spelling = match ty.Physical() {
        VdMirType::Void => "void",
        VdMirType::Scalar(VdMirScalar::Bool) => "bool",
        VdMirType::Scalar(VdMirScalar::I32) | VdMirType::Enum(_) => "int",
        VdMirType::Scalar(VdMirScalar::U32) => "uint",
        VdMirType::Scalar(VdMirScalar::F32) => "float",
        VdMirType::FloatVector(width) => return format!("float{width}"),
        VdMirType::UintVector(width) => return format!("uint{width}"),
        VdMirType::StorageArray { Element, Writable } => {
            return HlslStorageType(*Element, *Writable);
        }
        VdMirType::Float4x4 => "float4x4",
        VdMirType::Aggregate(name) => name,
        VdMirType::Array { Element, Length } => return format!("{}[{Length}]", HlslType(Element)),
        VdMirType::String => "string",
        VdMirType::Unresolved => unreachable!("MIR declaration and conversion types are resolved"),
        VdMirType::Nominal { .. } => unreachable!("physical types have no nominal wrapper"),
    };
    spelling.to_string()
}
